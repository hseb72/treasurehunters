/** Entrée du dictionnaire, sans tenir compte de la majuscule initiale. */
function loose(fr: string): string | undefined {
  const cap = fr.charAt(0).toUpperCase() + fr.slice(1);
  const hit = EN[fr] ?? EN[cap];
  return hit === undefined ? undefined : fr === cap ? hit : hit.charAt(0).toLowerCase() + hit.slice(1);
}

/** Traduit un morceau déjà connu du dictionnaire, sinon le laisse tel quel. */
const w = (fr: string): string => EN[fr] ?? fr;
const plural = (n: string, one: string, many: string) => (n === '1' ? one : many);
const ordinal = (n: string) => {
  const k = Number(n);
  const s = k % 100 >= 11 && k % 100 <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string>)[k % 10] ?? 'th';
  return `${k}${s}`;
};

