/** Traduction d'un texte de l'interface : dictionnaire, puis modèles ; null si inconnu. */
export function translateUi(text: string): string | null {
  const direct = EN[text];
  if (direct !== undefined) return direct;
  for (const [re, rep] of EN_PATTERNS) {
    const m = re.exec(text);
    if (!m) continue;
    const out = typeof rep === 'string' ? text.replace(re, rep) : rep(...(m as unknown as string[]));
    // Un modèle qui rend le texte tel quel ne sait pas le traduire : on essaie les suivants.
    if (out !== text) return out;
  }
  return null;
}
