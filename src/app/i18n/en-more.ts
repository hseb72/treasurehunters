const at = (s: string) => s.replace(/ à (\d)/, ' at $1');
const plural = (n: string, one: string, many: string) => (n === '1' ? one : many);
const ordinal = (n: string) => {
  const k = Number(n);
  const s = k % 100 >= 11 && k % 100 <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string>)[k % 10] ?? 'th';
  return `${k}${s}`;
};

